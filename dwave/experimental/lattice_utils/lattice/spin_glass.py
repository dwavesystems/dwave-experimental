from __future__ import annotations

from collections.abc import Callable, Hashable
from functools import partial
from numbers import Integral
from typing import Protocol

import dimod
import numpy as np
from numpy.typing import NDArray


class SpinGlassLattice(Protocol):
    precision: int
    edge_list: list[tuple[Hashable, Hashable]]


def generate_spin_glass_couplings(lattice: SpinGlassLattice, seed: int) -> tuple[NDArray, str]:
    """Generate seeded, discrete spin-glass couplings for each lattice edge.

    Precision 1 produces equally likely -1 and +1 couplings. Even
    precisions greater than 1 produce positive and negative magnitudes
    from 1 / (precision / 2) through 1.

    Args:
        lattice: A lattice object with a precision attribute and an edge_list attribute.
        seed: An integer seed for the random number generator.

    Returns:
        A tuple containing an array of couplings and a string identifying the instance type.
    """
    rng = np.random.default_rng(seed)

    if lattice.precision == 1:
        values = rng.integers(0, 2, size=len(lattice.edge_list))
        couplings = 2 * values - 1
    else:
        half = lattice.precision // 2
        values = rng.integers(0, lattice.precision, size=len(lattice.edge_list))
        sign = np.where(values < half, 1, -1)
        magnitude = values % half + 1
        couplings = sign * magnitude / half

    return couplings, f"seeded_discrete_p{lattice.precision}"


class SpinGlassMixin:
    """Add seeded spin-glass couplings to a lattice.

    By default, precision 1 produces ±1 couplings; positive even precisions
    produce uniformly sampled discrete signed couplings. A custom coupling
    function can override this distribution.
    """

    def __init__(
        self,
        precision: int = 1,
        coupling_function: Callable[[SpinGlassLattice, int], tuple[NDArray, str]] | None = None,
        **kwargs,
    ):
        if not isinstance(precision, Integral) or isinstance(precision, bool):
            raise TypeError(f"precision must be an integer, got {precision!r}")
        if precision != 1 and (precision < 2 or precision % 2 != 0):
            raise ValueError(f"precision must be 1 or a positive even integer, got {precision}")
        self.precision = int(precision)

        if coupling_function is None:
            coupling_function = generate_spin_glass_couplings
        self.coupling_function = partial(coupling_function, self)

        super().__init__(**kwargs)

        self.glass_string = self._make_glass_string()

    def make_bqm(self, seed: int = 0) -> dimod.BQM:
        """Construct a spin BQM with zero biases and seeded couplings on lattice edges.

        Args:
            seed: Integer seed for the random number generator used to generate couplings.

        Returns:
            A dimod.BQM object representing the spin-glass Hamiltonian with
            couplings generated by the coupling function.
        """
        bqm = dimod.BQM(vartype="SPIN")
        for v in range(self.num_spins):
            bqm.add_variable(v)

        couplings = self.coupling_function(seed=seed)[0]
        for i, edge in enumerate(self.edge_list):
            bqm.add_quadratic(edge[0], edge[1], couplings[i])

        return bqm

    def _make_glass_string(self):
        """Return a string identifying the instance type for this lattice."""
        return "c_" + self.coupling_function(seed=0)[1]

    def _get_instance_pathstring(self) -> str:
        """Return a string representing the path to the instance data for this lattice."""
        return f"{super()._get_instance_pathstring()}/{self.glass_string}"
